"""JSON-file persistence: one file per life, written atomically."""

from __future__ import annotations

import logging
import os
import re
from pathlib import Path

from pydantic import ValidationError

from mortal.core.models import LifeState

log = logging.getLogger(__name__)
_ID = re.compile(r"^[a-f0-9]{8}$")


class LifeStore:
    def __init__(self, data_dir: Path):
        self.dir = data_dir
        self.dir.mkdir(parents=True, exist_ok=True)

    def _path(self, life_id: str) -> Path:
        if not _ID.match(life_id):  # ids are generated by us; this blocks path tricks
            raise ValueError(f"invalid life id {life_id!r}")
        return self.dir / f"{life_id}.json"

    def save(self, state: LifeState) -> None:
        path = self._path(state.id)
        tmp = path.with_suffix(".json.tmp")
        tmp.write_text(state.model_dump_json(), encoding="utf-8")
        os.replace(tmp, path)

    def delete(self, life_id: str) -> None:
        self._path(life_id).unlink(missing_ok=True)

    def load_all(self) -> list[LifeState]:
        states: list[LifeState] = []
        for path in sorted(self.dir.glob("*.json")):
            if not _ID.match(path.stem):
                continue
            try:
                states.append(LifeState.model_validate_json(path.read_text(encoding="utf-8")))
            except (OSError, ValidationError) as exc:
                log.warning("skipping unreadable life file %s: %s", path.name, exc)
        return states
